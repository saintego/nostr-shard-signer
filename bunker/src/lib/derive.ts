// Key derivation for v1 (#73, D2). Frozen at launch: a later version adds new
// labels and keeps deriving these, so identities never move.
//
//   root          = HKDF(global login key, "nostr-shard-signer/v1/root")
//   identity i    = HKDF(root, "nostr-shard-signer/v1/identity/" + i)
//   marker key    = HKDF(root, "nostr-shard-signer/v1/site-marker/" + canonical origin)
//   store key     = HKDF(root, "nostr-shard-signer/v1/site-store/" + canonical origin)
//   counter, config, backup keys: HKDF(root, "nostr-shard-signer/v1/<name>")
//   settings key  = HKDF(Evolustr master secret M, "nostr-shard-signer/v1/settings")  (D20)
//
// HKDF is HKDF-SHA256 (RFC 5869) with an empty salt, the label as `info` and 32
// bytes of output. WebCrypto only, so every browser runs the same code; the
// test vectors (C12) are generated by Node's own HKDF implementation.

export const LABEL_PREFIX = 'nostr-shard-signer/v1/';

/**
 * The origin's canonical form (D2): scheme and host lowercase, default port
 * dropped, internationalised names as punycode. That is exactly the WHATWG URL
 * origin, which every browser implements; anything else is refused.
 */
export function canonicalOrigin(input: string): string {
    let url: URL;
    try {
        url = new URL(input);
    } catch (_) {
        throw new Error(`Not an origin: ${input}`);
    }
    if (url.protocol !== 'https:' && url.protocol !== 'http:') throw new Error(`Not a web origin: ${input}`);
    if (url.origin === 'null') throw new Error(`Opaque origin: ${input}`);
    return url.origin;
}

export const labels = {
    root: LABEL_PREFIX + 'root',
    identity: (i: number) => {
        if (!Number.isSafeInteger(i) || i < 0) throw new Error(`Bad identity index: ${i}`);
        return LABEL_PREFIX + 'identity/' + i;
    },
    siteMarker: (origin: string) => LABEL_PREFIX + 'site-marker/' + canonicalOrigin(origin),
    siteStore: (origin: string) => LABEL_PREFIX + 'site-store/' + canonicalOrigin(origin),
    counter: LABEL_PREFIX + 'counter',
    config: LABEL_PREFIX + 'config',
    backup: LABEL_PREFIX + 'backup',
    settings: LABEL_PREFIX + 'settings',
} as const;

const SECP256K1_N = 0xfffffffffffffffffffffffffffffffebaaedce6af48a03bbfd25e8cd0364141n;

const toBigInt = (b: Uint8Array) => b.reduce((n, x) => (n << 8n) | BigInt(x), 0n);

/** HKDF-SHA256, empty salt, `label` as info, 32 bytes. */
export async function hkdf(ikm: Uint8Array, label: string): Promise<Uint8Array> {
    if (ikm.length !== 32) throw new Error('Input key must be 32 bytes');
    const key = await crypto.subtle.importKey('raw', ikm as BufferSource, 'HKDF', false, ['deriveBits']);
    const bits = await crypto.subtle.deriveBits(
        { name: 'HKDF', hash: 'SHA-256', salt: new Uint8Array(0), info: new TextEncoder().encode(label) },
        key,
        256,
    );
    return new Uint8Array(bits);
}

/**
 * A secp256k1 secret key from HKDF. An output of 0 or ≥ n (chance about 2^-128)
 * is derived again with "/retry" appended, until valid.
 */
export async function deriveSecretKey(ikm: Uint8Array, label: string): Promise<Uint8Array> {
    for (let l = label; ; l += '/retry') {
        const k = await hkdf(ikm, l);
        const n = toBigInt(k);
        if (n > 0n && n < SECP256K1_N) return k;
    }
}

export const deriveRoot = (globalLoginKey: Uint8Array) => deriveSecretKey(globalLoginKey, labels.root);
export const deriveIdentity = (root: Uint8Array, i: number) => deriveSecretKey(root, labels.identity(i));
export const deriveMarkerKey = (root: Uint8Array, origin: string) => deriveSecretKey(root, labels.siteMarker(origin));
export const deriveStoreKey = (root: Uint8Array, origin: string) => hkdf(root, labels.siteStore(origin));
export const deriveCounterKey = (root: Uint8Array) => deriveSecretKey(root, labels.counter);
export const deriveConfigKey = (root: Uint8Array) => deriveSecretKey(root, labels.config);
export const deriveBackupKey = (root: Uint8Array) => hkdf(root, labels.backup);
export const deriveSettingsKey = (m: Uint8Array) => hkdf(m, labels.settings);
